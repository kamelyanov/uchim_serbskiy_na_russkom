    for sr, ru in pairs:
        assign(sr, ru)
    lines = []
    total = 0
    order = [name for name, _ in TOPICS] + FALLBACK
    for name in order:
        items = groups[name]
        lines.append(f"### {name} ({len(items)})")
        lines.extend(f"{sr} - {ru}" for sr, ru in items)
        lines.append("")
        total += len(items)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"сгруппировано: {total}")
    for name in order:
        print(f"  {name}: {len(groups[name])}")

