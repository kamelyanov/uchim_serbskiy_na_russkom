def kw_hit(words, phrase, k):
    if " " in k:
        return (" " + k) in phrase or phrase.startswith(k + " ") or (" " + k + " ") in phrase
    kl = k.lower()
    for w in words:
        if w in BAN:
            continue
        if len(kl) >= 4:
            if w.startswith(kl):
                return True
        else:
            for e in INFL:
                if w == kl + e:
                    return True
    return False

def assign(sr, ru):
    s = f"{sr} {ru}".lower()
    words = s.split()
    for name, keys in TOPICS:
        for k in keys:
            if kw_hit(words, s, k):
                groups[name].append((sr, ru))
                return
    sr_l = sr.lower()
    ru_l = ru.lower()
    if ru_l in FUNC_WORDS:
        groups["Служебные слова"].append((sr, ru))
    elif sr_l.endswith(VERB_SUFFIXES) or ru_l.endswith(("ть", "ться", "тся")):
        groups["Глаголы общего значения"].append((sr, ru))
    elif ru_l.endswith(ADJ_RU_ENDINGS) and sr_l.endswith(ADJ_SR_ENDINGS):
        groups["Прилагательные общего значения"].append((sr, ru))
    elif sr_l.endswith("o") and ru_l.endswith(("о", "е")):
        groups["Наречия"].append((sr, ru))
    else:
        groups["Прочие существительные"].append((sr, ru))

