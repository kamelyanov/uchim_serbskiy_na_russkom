def load():
    seen = {}
    dropped = 0
    for f in FILES:
        for raw in f.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            m = pair_re.match(line)
            if not m:
                if line:
                    dropped += 1
                continue
            sr, ru = m.group(1), m.group(2)
            # отбросить строки, начинающиеся со словарной пометы ("грам имя прилагательное")
            tm = tag_start_re.match(ru)
            if tm and tm.group(1) in TAGS:
                dropped += 1
                continue
            # отбросить, если вся русская часть — помета
            if ru in TAGS:
                dropped += 1
                continue
            if is_corrupt(ru):
                dropped += 1
                continue
            key = (sr.lower(), ru.lower())
            if key not in seen:
                seen[key] = (sr, ru)
    return list(seen.values()), dropped

